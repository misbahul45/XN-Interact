import { join } from "node:path";
import { Client } from "@modelcontextprotocol/client";
import { StdioClientTransport } from "@modelcontextprotocol/client/stdio";
import { TOKENIZER, registryStats, type ToolListEntry } from "../src/performance/benchmark.ts";
import { SCENARIOS } from "../tests/perf/scenarios.ts";
import { ROOT, tempHome, testEnv } from "../tests/helpers.ts";

const c = new Client({ name: "bench", version: "1" });
await c.connect(new StdioClientTransport({ command: process.execPath, args: [join(ROOT, "src/main.ts")], env: { ...testEnv(tempHome(), { XN_INTERACT_KEYRING: "file" }), PATH: process.env.PATH ?? "" }, stderr: "pipe" }));
const tools = (await c.listTools()).tools as ToolListEntry[];
await c.close();
const reg = registryStats(tools);
const rows: string[] = [];
for (const sc of SCENARIOS) {
  const compact = await sc.run("compact");
  const detailed = ["list_accounts", "inspect_capability", "read_paginated", "write_timeout"].includes(sc.id) ? await sc.run("detailed") : null;
  rows.push(`| ${sc.title} | ${compact.calls} | ${compact.arg_tokens} | ${compact.out_tokens} | ${compact.total_tokens} | ${detailed ? detailed.total_tokens : "same"} |`);
}
const out = `# Token benchmark: server-controllable part (P9-01)

Generated by \`bun scripts/bench.ts\`. Tokenizer: ${TOKENIZER.name} ${TOKENIZER.version} (${TOKENIZER.encoding}). ${TOKENIZER.caveat}

## What this measures

Tokens a host must read to discover the tools and to complete each canonical task against the fixture provider: the JSON arguments it sends and the JSON envelope it gets back. One run per scenario; counts vary by a few tokens because identifiers are random.

## What it does not measure

Success rate, host deliberation turns, the host's own tool-wrapping overhead, real provider payloads, and the 14-, 31- and per-provider variants. Those need a model in the loop or later tasks (P9-02, P9-03), so there is **no** tokens-per-successful-task figure yet.

## Registry (\`tools/list\` over real stdio, ${reg.tools} tools)

| Measure | Value |
|---|---|
| Bytes | ${reg.bytes} |
| Tokens | ${reg.tokens} |
| Mean tokens per tool | ${reg.per_tool_mean_tokens} |
| Largest tools | ${reg.largest.map((t) => `${t.name} (${t.tokens})`).join(", ")} |

The baseline's provisional target was under about 3,000 tokens for the initial registry. The first measurement was 7,321 tokens; 3,168 of them (43%) were an identical envelope \`outputSchema\` repeated on all 22 tools, which carries no per-tool information and was removed (4,153 now). Further reduction is task P9-04.

## Scenarios (compact profile unless noted)

| Scenario | Calls | Arg tokens | Output tokens | Total | Total with detailed profile |
|---|---:|---:|---:|---:|---:|
${rows.join("\n")}
`;
await Bun.write(join(ROOT, "docs/token-benchmarks.md"), out);
console.log(out);
