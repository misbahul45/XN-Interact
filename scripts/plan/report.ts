import type { Model, Phase, Requirement, Task } from "./model.ts";

export type PhaseState = "PLAN" | "IN_PROGRESS" | "DONE";

export function covering(m: Model, reqId: string): Task[] {
  return m.tasks.filter((t) => t.reqs.includes(reqId));
}

export function requirementVerified(m: Model, r: Requirement): boolean {
  const ts = covering(m, r.id);
  return ts.length > 0 && ts.every((t) => t.status === "VERIFIED");
}

export function gateSatisfied(m: Model, p: Phase): boolean {
  const reqs = p.gate.all_must ? m.requirements.filter((r) => r.priority === "MUST") : m.requirements.filter((r) => p.gate.requires.includes(r.id));
  const tasksOk = p.gate.tasks.every((id) => m.tasks.find((t) => t.id === id)?.status === "VERIFIED");
  return tasksOk && reqs.every((r) => requirementVerified(m, r));
}

export function phaseState(m: Model, p: Phase): PhaseState {
  const ts = m.tasks.filter((t) => t.phase === p.id);
  if (ts.every((t) => t.status === "VERIFIED" || t.status === "ARCHIVED") && gateSatisfied(m, p)) return "DONE";
  return ts.some((t) => t.status !== "PLAN") ? "IN_PROGRESS" : "PLAN";
}

export function readyTasks(m: Model): Task[] {
  const status = new Map(m.tasks.map((t) => [t.id, t.status]));
  return m.tasks.filter((t) => t.status === "PLAN" && t.deps.every((d) => status.get(d) === "VERIFIED"));
}

export function criticalPath(m: Model): Task[] {
  const byId = new Map(m.tasks.map((t) => [t.id, t]));
  const memo = new Map<string, string[]>();
  const visiting = new Set<string>();
  const longest = (id: string): string[] => {
    const hit = memo.get(id);
    if (hit) return hit;
    const t = byId.get(id);
    if (!t || visiting.has(id)) return [];
    visiting.add(id);
    let best: string[] = [];
    for (const d of t.deps) {
      const p = longest(d);
      if (p.length > best.length) best = p;
    }
    const own = t.status === "VERIFIED" || t.status === "ARCHIVED" ? [] : [id];
    const path = [...best, ...own];
    memo.set(id, path);
    return path;
  };
  const sinks = m.tasks.filter((t) => !m.tasks.some((o) => o.deps.includes(t.id)));
  let best: string[] = [];
  for (const s of sinks) {
    const p = longest(s.id);
    if (p.length > best.length) best = p;
  }
  return best.map((id) => byId.get(id)).filter((t): t is Task => Boolean(t));
}

function count(ts: Task[], s: Task["status"]): number {
  return ts.filter((t) => t.status === s).length;
}

function cell(text: string): string {
  return text.replaceAll("|", "\\|");
}

export function renderStatus(m: Model): string {
  const lines: string[] = [];
  const total = m.tasks.length;
  const done = count(m.tasks, "VERIFIED");
  const asOf = m.checkpoints.length ? m.checkpoints[m.checkpoints.length - 1]?.at ?? "none" : "none";
  lines.push("# XN-Interact implementation status");
  lines.push("");
  lines.push("Generated by `bun run plan:render` from `plan/*.json` and `plan/checkpoints.jsonl`. Do not edit by hand.");
  lines.push("");
  lines.push(`As of last checkpoint: ${asOf}`);
  lines.push("");
  const byPriority = (p: Requirement["priority"]) => {
    const rs = m.requirements.filter((r) => r.priority === p);
    return `${rs.filter((r) => requirementVerified(m, r)).length}/${rs.length}`;
  };
  lines.push(`- Tasks verified: ${done}/${total}`);
  lines.push(`- In progress: ${count(m.tasks, "IN_PROGRESS")}, blocked: ${count(m.tasks, "BLOCKED")}, awaiting approval: ${count(m.tasks, "APPROVAL_REQUESTED")}`);
  lines.push(`- Requirements verified: MUST ${byPriority("MUST")}, SHOULD ${byPriority("SHOULD")}, COULD ${byPriority("COULD")}`);
  lines.push("");
  lines.push("## Phases");
  lines.push("");
  lines.push("| Order | Phase | State | Verified | Active | Blocked | Gate |");
  lines.push("|---:|---|---|---:|---:|---:|---|");
  for (const p of [...m.phases].sort((a, b) => a.order - b.order)) {
    const ts = m.tasks.filter((t) => t.phase === p.id);
    const active = ts.filter((t) => ["IN_PROGRESS", "APPROVAL_REQUESTED", "APPROVED"].includes(t.status)).length;
    lines.push(`| ${p.order} | ${p.id} ${cell(p.title)} | ${phaseState(m, p)} | ${count(ts, "VERIFIED")}/${ts.length} | ${active} | ${count(ts, "BLOCKED")} | ${gateSatisfied(m, p) ? "passed" : "open"} |`);
  }
  lines.push("");
  const section = (title: string, ts: Task[], empty: string) => {
    lines.push(`## ${title}`);
    lines.push("");
    if (!ts.length) lines.push(empty);
    for (const t of ts) lines.push(`- \`${t.id}\` ${t.title} (${t.owner}${t.approval ? ", approval" : ""})${t.blocker ? ` — blocker: ${t.blocker}` : ""}`);
    lines.push("");
  };
  section("Ready now", readyTasks(m), "Nothing is ready.");
  section("In progress", m.tasks.filter((t) => t.status === "IN_PROGRESS" || t.status === "APPROVED"), "Nothing in progress.");
  section("Blocked", m.tasks.filter((t) => t.status === "BLOCKED"), "Nothing blocked.");
  section("Awaiting owner approval", m.tasks.filter((t) => t.status === "APPROVAL_REQUESTED"), "No approval requests.");
  const path = criticalPath(m);
  lines.push(`## Critical path (${path.length} open tasks)`);
  lines.push("");
  lines.push(path.length ? path.map((t) => `\`${t.id}\``).join(" → ") : "Complete.");
  lines.push("");
  lines.push("## Recent checkpoints");
  lines.push("");
  const recent = m.checkpoints.slice(-10).reverse();
  if (!recent.length) lines.push("None yet.");
  for (const cp of recent) lines.push(`- ${cp.at} \`${cp.task}\` ${cp.from} → ${cp.to} by ${cp.actor}${cp.via === "chat" ? ` (via chat, recorded by ${cp.recorded_by ?? "agent"}: "${cp.quote}")` : ""}${cp.note ? `: ${cp.note}` : ""}`);
  lines.push("");
  return lines.join("\n");
}
